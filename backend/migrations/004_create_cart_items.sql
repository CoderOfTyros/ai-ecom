CREATE TABLE IF NOT EXISTS cart_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, -- delete cart items if user is deleted
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT, -- block product deletion if it is in a cart

    quantity INTEGER NOT NULL CHECK (quantity >= 1 AND quantity <= 99),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_cart_items_user_id_product_id UNIQUE (user_id, product_id) -- in cart_items table, combination of user_id and product_id is unique
 
);

CREATE INDEX IF NOT EXISTS idx_cart_items_user_id ON cart_items(user_id);
CREATE INDEX IF NOT EXISTS idx_cart_items_product_id ON cart_items(product_id);

-- set_updated_at() already exists from 002_create_products.sql
DROP TRIGGER IF EXISTS trg_cart_items_updated_at ON cart_items;

CREATE TRIGGER trg_cart_items_updated_at
BEFORE UPDATE ON cart_items
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();